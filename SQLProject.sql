CREATE TABLE COURSES
(
COURSEID VARCHAR(50) PRIMARY KEY,
COURSENAME VARCHAR(50) UNIQUE,
CATEGORY VARCHAR(100),
COURSEFEE INT,
DIFFICULTYLEVEL VARCHAR(100) CHECK(DIFFICULTYLEVEL IN ('BEGINNER', 'INTERMEDIATE', 'ADVANCED')) DEFAULT 'BEGINNER'
)


CREATE TABLE ENROLLMENTS
(
ENROLLMENTID VARCHAR(50) PRIMARY KEY,
STUDENTID INT NOT NULL,
COURSEID VARCHAR(50) NOT NULL,
ENROLLMENTDATE DATE DEFAULT GETDATE(),
DISCOUNT DECIMAL(5,2) DEFAULT 0 CHECK(DISCOUNT >= 0 AND DISCOUNT <= 100),
PAYMENTSTATUS VARCHAR(50) CHECK(PAYMENTSTATUS IN ('PENDING','COMPLETED','FAILED')) DEFAULT 'PENDING',
FOREIGN KEY (STUDENTID)
REFERENCES STUDENTS(STUDENTID),
FOREIGN KEY (COURSEID)
REFERENCES COURSES(COURSEID)
)



CREATE TABLE PAYMENTS
(
PAYMENTID VARCHAR(100) PRIMARY KEY,
ENROLLMENTID VARCHAR(50) NOT NULL,
AMOUNTPAID DECIMAL(10,2) CHECK(AMOUNTPAID >= 0),
PAYMENTDATE DATETIME DEFAULT GETDATE(),
FOREIGN KEY (ENROLLMENTID)
REFERENCES ENROLLMENTS(ENROLLMENTID)
)


CREATE TABLE TRAINERS
(
TRAINERID INT PRIMARY KEY,
TRAINERNAME VARCHAR(100) NOT NULL,
EXPERTISE VARCHAR(100),
SATISFACTIONSCORE DECIMAL(3,2) CHECK(SATISFACTIONSCORE BETWEEN 0 AND 5)
)

CREATE TABLE TRAINER_COURSE_MAPPING
(
MAPPINGID INT PRIMARY KEY,
TRAINERID INT NOT NULL,
COURSEID VARCHAR(50) NOT NULL,
ASSIGNEDDATE DATETIME DEFAULT GETDATE(),
FOREIGN KEY(TRAINERID)
REFERENCES TRAINERS(TRAINERID),
FOREIGN KEY(COURSEID)
REFERENCES COURSES(COURSEID),
UNIQUE(TRAINERID, COURSEID)
)

CREATE TABLE MARKETING
(
MARKETINGID INT PRIMARY KEY,
MONTHYEAR VARCHAR(50) NOT NULL,
CHANNEL VARCHAR(50) CHECK(CHANNEL IN('INSTAGRAM','YOUTUBE','GOOGELADS','FACEBOOK')),
SPEND DECIMAL(10,2) CHECK(SPEND >= 0),
LEADSGENERATED INT CHECK(LEADSGENERATED >= 0)
);


