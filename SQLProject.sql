--Produce SQL results for:
--CAC (Cost per Acquisition)- ROI per marketing channel

SELECT
    M.CHANNEL,
    SUM(M.SPEND) AS TOTAL_SPEND,
    COUNT(E.ENROLLMENTID) AS TOTAL_ENROLLMENTS,
    SUM(M.SPEND) / COUNT(E.ENROLLMENTID) AS CAC

FROM MARKETING M

LEFT JOIN ENROLLMENTS E
ON FORMAT(E.ENROLLMENTDATE,'yyyy-MM') = M.MONTHYEAR

GROUP BY M.CHANNEL

HAVING COUNT(E.ENROLLMENTID) > 0

ORDER BY CAC

--- 12 month enrollment heatmap (Month × City) 

SELECT
    FORMAT(E.ENROLLMENTDATE,'yyyy-MM') AS MONTHYEAR,
    S.CITY,
    COUNT(E.ENROLLMENTID) AS TOTAL_ENROLLMENTS

FROM ENROLLMENTS E

INNER JOIN STUDENTS S
ON E.STUDENTID = S.STUDENTID

GROUP BY
FORMAT(E.ENROLLMENTDATE,'yyyy-MM'),
S.CITY

ORDER BY
MONTHYEAR,
TOTAL_ENROLLMENTS DESC

--- Top course & worst course by revenue 
SELECT
    TOP 1
    E.COURSEID,
    SUM(P.AMOUNTPAID) AS TOTAL_REVENUE

