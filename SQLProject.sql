--Step 2: Stored Procedure with TRY...CATCH
CREATE PROCEDURE SP_MONTHLYREVENUE_ERRORHANDLING

    @MONTH INT

AS
BEGIN

    BEGIN TRY

        IF @MONTH < 1 OR @MONTH > 12
            THROW 50001, 'Invalid month entered.', 1;

        SELECT
            SUM(AMOUNTPAID) AS TOTAL_REVENUE
        FROM PAYMENTS
        WHERE MONTH(PAYMENTDATE) = @MONTH;

    END TRY

    BEGIN CATCH

        INSERT INTO ERRORLOG
        (
            ERRORMESSAGE
        )
        VALUES
        (
