CREATE FUNCTION fn_NetFeeAfterDiscount
(
    @CourseFee DECIMAL(10,2),
    @Discount DECIMAL(10,2)
)

RETURNS DECIMAL(10,2)

AS
BEGIN

    DECLARE @NetFee DECIMAL(10,2)

    SET @NetFee =
    @CourseFee - (@CourseFee * @Discount / 100)

