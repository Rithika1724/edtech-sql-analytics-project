-- PART 8 — WINDOW FUNCTIONS 
--- RANK() revenue per month 

SELECT
MONTH(PAYMENTDATE) AS MONTH_NUMBER,
SUM(AMOUNTPAID) AS TOTAL_REVENUE,

RANK() OVER
(
    ORDER BY SUM(AMOUNTPAID) DESC
) AS REVENUE_RANK

FROM PAYMENTS

GROUP BY MONTH(PAYMENTDATE)

-- DENSE_RANK() — Top 3 courses per month

SELECT
MONTH(P.PAYMENTDATE) AS MONTH_NUMBER,
E.COURSEID,
SUM(P.AMOUNTPAID) AS TOTAL_REVENUE,

DENSE_RANK() OVER
(
    PARTITION BY MONTH(P.PAYMENTDATE)

    ORDER BY SUM(P.AMOUNTPAID) DESC
) AS COURSE_RANK

FROM PAYMENTS P

INNER JOIN ENROLLMENTS E
ON P.ENROLLMENTID = E.ENROLLMENTID

GROUP BY
MONTH(P.PAYMENTDATE),
E.COURSEID

-- LAG() — Month-over-month revenue change
-- Compare current month revenue with previous month

SELECT
MONTH(PAYMENTDATE) AS MONTH_NUMBER,

SUM(AMOUNTPAID) AS CURRENT_MONTH_REVENUE,

LAG(SUM(AMOUNTPAID))
OVER
(
    ORDER BY MONTH(PAYMENTDATE)
) AS PREVIOUS_MONTH_REVENUE

FROM PAYMENTS

GROUP BY MONTH(PAYMENTDATE)

-- LEAD() to forecast next month trend
SELECT
MONTH(PAYMENTDATE) AS MONTH_NUMBER,

SUM(AMOUNTPAID) AS CURRENT_MONTH_REVENUE,

LEAD(SUM(AMOUNTPAID))
OVER
(
    ORDER BY MONTH(PAYMENTDATE)
) AS NEXT_MONTH_REVENUE

FROM PAYMENTS

GROUP BY MONTH(PAYMENTDATE)

