--2. Adding a new student with validation (INOUT) 

CREATE PROCEDURE sp_AddStudent
(
    @StudentID INT,
    @FullName VARCHAR(100),
    @Email VARCHAR(100),
    @Phone VARCHAR(20),
    @City VARCHAR(50),
    @State VARCHAR(50),
    @Message VARCHAR(100) OUTPUT
)
AS
BEGIN

    IF EXISTS
    (
        SELECT *
        FROM Students
        WHERE Email = @Email
    )

    BEGIN
        SET @Message='Email already exists'
    END

    ELSE

    BEGIN

        INSERT INTO Students
        (
            StudentID,
            FullName,
            Email,
            Phone,
            City,
            State
        )

        VALUES
        (
            @StudentID,
            @FullName,
            @Email,
            @Phone,
            @City,
            @State
        )

        SET @Message='Student Added Successfully'

    END

END



